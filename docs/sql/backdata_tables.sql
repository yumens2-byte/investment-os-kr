-- 보안: docs/sql/fb_reply_tables.sql과 같은 정책을 따른다 (D-4).
--       레포 Secret SUPABASE_KEY(anon)를 사용하고, RLS는 해제하되 anon에는 필요한 최소 권한만
--       부여한다 (post = SELECT/INSERT/UPDATE, metrics = SELECT/INSERT). DELETE/TRUNCATE 없음.
-- 중복 방지: UNIQUE(trade_date, mode) = 거래일당 1건, UNIQUE(text_hash, mode) = 같은 문구 재발행 금지.
-- 적용 후 CHECK 제약은 실측한다 (STD-DB-04). 기존 kr_* 테이블은 변경하지 않는다.
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.kr_backdata_post (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trade_date     date        NOT NULL,
  mode           varchar     NOT NULL,
  format         varchar     NOT NULL DEFAULT 'reversal_card',
  condition_key  varchar     NOT NULL,
  stats_json     jsonb       NOT NULL,
  text_x         text        NOT NULL,
  text_fb        text        NOT NULL,
  text_hash      varchar(64) NOT NULL,
  hook_source    varchar,
  version        varchar,
  x_status       varchar     NOT NULL DEFAULT 'pending',
  x_post_id      text,
  x_posted_at    timestamptz,
  x_error        text,
  fb_status      varchar     NOT NULL DEFAULT 'pending',
  fb_post_id     text,
  fb_posted_at   timestamptz,
  fb_error       text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT kr_backdata_post_day_uniq  UNIQUE (trade_date, mode),
  CONSTRAINT kr_backdata_post_text_uniq UNIQUE (text_hash, mode),
  CONSTRAINT kr_backdata_post_mode_chk  CHECK (mode IN ('shadow', 'live')),
  CONSTRAINT kr_backdata_post_xs_chk
    CHECK (x_status IN ('pending', 'posted', 'failed', 'unknown', 'skipped')),
  CONSTRAINT kr_backdata_post_fs_chk
    CHECK (fb_status IN ('pending', 'posted', 'failed', 'unknown', 'skipped'))
);
CREATE INDEX IF NOT EXISTS idx_kr_backdata_post_created
  ON public.kr_backdata_post USING btree (created_at DESC);

CREATE TABLE IF NOT EXISTS public.kr_backdata_metrics (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id        bigint      NOT NULL REFERENCES public.kr_backdata_post (id),
  channel        varchar     NOT NULL,
  checkpoint     varchar     NOT NULL,
  elapsed_hours  numeric,
  impressions    integer,
  engagements    integer,
  raw            jsonb,
  collected_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT kr_backdata_metrics_uniq UNIQUE (post_id, channel, checkpoint),
  CONSTRAINT kr_backdata_metrics_ch_chk CHECK (channel IN ('x', 'fb')),
  CONSTRAINT kr_backdata_metrics_cp_chk CHECK (checkpoint IN ('first', 'final'))
);

COMMENT ON TABLE  public.kr_backdata_post    IS 'DN2026_0090 백데이터 반전 카드 발행 원장 (pending 선기록)';
COMMENT ON TABLE  public.kr_backdata_metrics IS 'DN2026_0090 게시물 성과 (24h first / 72h final). 참여율은 조회 시 계산';
COMMENT ON COLUMN public.kr_backdata_metrics.impressions IS 'X: organic→non_public→public impression_count / FB: post_media_view';
COMMENT ON COLUMN public.kr_backdata_metrics.engagements IS 'X: like+reply+retweet+quote+bookmark / FB: post_clicks + 반응 합계';

ALTER TABLE public.kr_backdata_post    DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.kr_backdata_metrics DISABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.kr_backdata_post, public.kr_backdata_metrics FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.kr_backdata_post TO anon;
GRANT SELECT, INSERT ON public.kr_backdata_metrics TO anon;
GRANT USAGE, SELECT ON SEQUENCE public.kr_backdata_post_id_seq,
                                public.kr_backdata_metrics_id_seq TO anon;
